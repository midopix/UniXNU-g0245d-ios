#!/usr/bin/env python3
"""Make the xnu work tree host-independent: doconf's interpreter.

The consolidated patches were generated on a machine whose csh lives at
/home/myth/.workbuddy/binaries/gitlocal/bin/tcsh, and that absolute path
travelled into them.  On any other host the interpreter does not exist, so
make reports

    make[5]: .../SETUP/config/doconf: No such file or directory   (Error 127)

which reads like a missing file but is really a dead shebang: doconf is a csh
script and every component Makefile is generated by running it.

This rewrites the interpreter to the first csh/tcsh that exists on this host.
It touches nothing that ends up in the kernel, so it does not change the
built image -- it only makes the build able to run.

Usage:
    XNU_WORK=... python3 scripts/linux/fix_host_paths.py
"""
import os
import sys

WORK = os.environ.get("XNU_WORK")
if not WORK:
    sys.exit("set XNU_WORK to the xnu-work tree")

DOCONF = os.path.join(WORK, "SETUP/config/doconf")

CANDIDATES = [
    os.path.expanduser("~/.workbuddy/binaries/gitlocal/bin/tcsh"),
    "/usr/bin/tcsh",
    "/usr/bin/csh",
    "/bin/csh",
]


def pick_interpreter():
    for c in CANDIDATES:
        if os.path.isfile(c) and os.access(c, os.X_OK):
            return c
    return None


def main():
    if not os.path.isfile(DOCONF):
        print("doconf not found at %s (tree not prepared?)" % DOCONF)
        return 0

    interp = pick_interpreter()
    if interp is None:
        print("no csh/tcsh found; install one (Ubuntu: apt install csh)")
        return 1

    with open(DOCONF, encoding="utf-8", errors="surrogateescape") as f:
        s = f.read()
    if not s.startswith("#!"):
        print("doconf: no shebang, nothing to do")
        return 0

    old = s.splitlines()[0]
    new = "#!%s -f" % interp
    if old == new:
        print("doconf: shebang already %s" % interp)
        return 0

    s = s.replace(old, new, 1)
    with open(DOCONF, "w", encoding="utf-8", errors="surrogateescape") as f:
        f.write(s)
    os.chmod(DOCONF, 0o755)
    print("doconf: shebang %s -> %s" % (old, new))
    return 0


if __name__ == "__main__":
    sys.exit(main())
