#!/usr/bin/env python3
"""Extract the vendor UFS facts out of the stock G0245D firmware.

Answer to a recurring question: "can the UFS driver be pulled out of the OEM
image?"  The short version is yes for *facts and reference code identity*, no
for *loadable code*.  This script produces the facts.

Two inputs, both of which we already keep locally:

  --boot-img  assets/stock-boot-trimmed.img
              Android boot.img.  Its payload is the vendor Linux kernel
              (gzip'd arm64 Image).  The kernel embeds the OEM build path of
              drivers/scsi/ufs/*, which identifies the exact upstream tree, plus
              every clock name, printk message and PHY variant string.

  --dtb       the stock board device tree (g0245d.dtb)
              Carries the live 'ufshc@624000' / 'ufsphy@627000' nodes: MMIO
              windows, SPI, lanes, rails, the 11 clock inputs, the UFS PHY
              variant.  This is board data we would otherwise have to guess.

Output is a markdown data sheet on stdout (or --out FILE).

No vendor code is copied by this script; it only reports strings and numbers so
the port can be written against the real CAF source of the same release.
"""

import argparse
import re
import struct
import sys
import zlib


# ---------------------------------------------------------------- boot.img ---

def boot_kernel(path):
    with open(path, "rb") as f:
        d = f.read()
    if d[:8] != b"ANDROID!":
        raise SystemExit(f"{path}: not an Android boot image")
    kernel_size = struct.unpack_from("<I", d, 8)[0]
    page_size = struct.unpack_from("<I", d, 36)[0]
    cmdline = d[0x40:0x240].split(b"\0")[0].decode("latin-1", "replace")
    blob = d[page_size:page_size + kernel_size]
    if blob[:2] != b"\x1f\x8b":
        raise SystemExit("kernel is not gzip'd; extend boot_kernel() for this format")
    # gzip member followed by padding/other data: stop at the first member end.
    raw = zlib.decompressobj(16 + zlib.MAX_WBITS).decompress(blob)
    return cmdline, page_size, blob, raw


# --------------------------------------------------------------------- dtb ---

def fdt_parse(path):
    with open(path, "rb") as f:
        d = f.read()
    (magic, _total, off_struct, off_strings, _off_rsv,
     _ver, _lcv, _boot, sz_str, _sz_struct) = struct.unpack(">10I", d[:40])
    if magic != 0xD00DFEED:
        raise SystemExit(f"{path}: bad FDT magic")
    strtab = d[off_strings:off_strings + sz_str]

    def name_at(off):
        end = strtab.find(b"\0", off)
        return strtab[off:end].decode("utf-8", "replace")

    i, path_parts, nodes = off_struct, [], []
    while True:
        tok = struct.unpack_from(">I", d, i)[0]
        i += 4
        if tok == 1:  # FDT_BEGIN_NODE
            end = d.find(b"\0", i)
            node = d[i:end].decode("utf-8", "replace")
            i = (end + 1 + 3) & ~3
            if node:
                path_parts.append(node)
            nodes.append(("/".join(path_parts), []))
        elif tok == 2:  # FDT_END_NODE
            if path_parts:
                path_parts.pop()
        elif tok == 3:  # FDT_PROP
            length, nameoff = struct.unpack_from(">II", d, i)
            i += 8
            value = d[i:i + length]
            i = (i + length + 3) & ~3
            if nodes:
                nodes[-1][1].append((name_at(nameoff), value))
        elif tok == 4:  # FDT_NOP
            pass
        elif tok == 9:  # FDT_END
            break
        else:
            raise SystemExit(f"{path}: bad FDT token {tok:#x} at {i - 4:#x}")
    return nodes


def be32(value):
    return list(struct.unpack(">%dI" % (len(value) // 4), value)) if len(value) % 4 == 0 else []


def cstr(value):
    return value.rstrip(b"\0").decode("utf-8", "replace")


def cstr_list(value):
    return [x.decode("utf-8", "replace") for x in value.split(b"\0") if x]


def find_node(nodes, suffix):
    for path, props in nodes:
        if path.endswith(suffix):
            return path, dict(props)
    return None, {}


# ------------------------------------------------------------------- report ---

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--boot-img", required=True)
    ap.add_argument("--dtb", required=True)
    ap.add_argument("--out")
    args = ap.parse_args()

    cmdline, page_size, blob, kimg = boot_kernel(args.boot_img)
    nodes = fdt_parse(args.dtb)

    lines = []
    add = lines.append

    add("# Vendor UFS facts extracted from the stock G0245D firmware")
    add("")
    add("Generated by `scripts/linux/extract-ufs-facts.py`.  Nothing here is")
    add("guesswork: every number comes out of the files named below.")
    add("")

    # --- kernel identity ---------------------------------------------------
    add("## 1. Vendor kernel identity")
    add("")
    add(f"- boot image: `{args.boot_img}`")
    add(f"- Android header: page size {page_size}, gzip payload {len(blob)} B -> "
        f"{len(kimg)} B arm64 Image")
    add(f"- boot cmdline: `{cmdline}`")
    version = re.search(rb"Linux version ([^\x00]{0,120})", kimg)
    add(f"- banner: `{version.group(1).decode('latin-1') if version else 'not found'}`")
    paths = sorted({m.decode("latin-1") for m in
                    re.findall(rb"/[A-Za-z0-9_./-]*drivers/(?:scsi/ufs|phy/qualcomm)[A-Za-z0-9_./-]*", kimg)})
    add("- embedded source paths (these identify the tree the OEM built):")
    for p in paths:
        add(f"  - `{p}`")
    if not paths:
        add("  - (none: kernel was built without CONFIG_IKCONFIG-style path strings)")
    add("")

    # --- clock / regulator names -------------------------------------------
    add("## 2. Clock, regulator and PHY strings present in the vendor kernel")
    add("")
    wanted = re.compile(rb"gcc_[a-z0-9_]*ufs[a-z0-9_]*|clk-gcc-ufs[a-z0-9_-]*|"
                        rb"qcom,ufs-phy-qmp-[a-z0-9]+|ufshcd_[a-z_]+|ufs_qcom_[a-z_]+")
    hits = sorted({m.decode() for m in wanted.findall(kimg)})
    for h in hits:
        add(f"- `{h}`")
    add("")

    # --- host controller node ---------------------------------------------
    hc_path, hc = find_node(nodes, "ufshc@624000")
    add("## 3. Host controller node from the stock board DTB")
    add("")
    if not hc:
        add("_ufshc@624000 not present in this DTB_")
    else:
        add(f"node: `{hc_path}`")
        add("")
        add("| property | value |")
        add("|---|---|")
        if "compatible" in hc:
            add(f"| compatible | {', '.join(cstr_list(hc['compatible']))} |")
        if "reg" in hc:
            base, size = be32(hc["reg"])[:2]
            add(f"| reg | 0x{base:x} + 0x{size:x} |")
        if "interrupts" in hc:
            v = be32(hc["interrupts"])
            add(f"| interrupts | {' '.join(hex(x) for x in v)} (GIC SPI {v[1] if len(v) > 1 else '?'}) |")
        add(f"| lanes-per-direction | {be32(hc.get('lanes-per-direction', b''))} |".replace("[]", "(absent)"))
        if "clock-names" in hc:
            add(f"| clock-names | {', '.join(cstr_list(hc['clock-names']))} |")
        n_clocks = len(hc.get("clocks", b"")) // 8
        add(f"| clocks | {n_clocks} phandle+index pairs |")
        if "freq-table-hz" in hc:
            add(f"| freq-table-hz | {be32(hc['freq-table-hz'])} |")
        rails = [k for k in hc if k.endswith("-supply")]
        if rails:
            add(f"| rails | {', '.join(rails)} |")
        add(f"| status | {cstr(hc.get('status', b''))} |")
    add("")

    # --- PHY node ---------------------------------------------------------
    phy_path, phy = find_node(nodes, "ufsphy@627000")
    add("## 4. UFS PHY node from the stock board DTB")
    add("")
    if not phy:
        add("_ufsphy@627000 not present in this DTB_")
    else:
        add(f"node: `{phy_path}`")
        add("")
        add("| property | value |")
        add("|---|---|")
        if "compatible" in phy:
            add(f"| compatible | {', '.join(cstr_list(phy['compatible']))} |")
        if "reg" in phy:
            base, size = be32(phy["reg"])[:2]
            add(f"| reg | 0x{base:x} + 0x{size:x} |")
        if "clock-names" in phy:
            add(f"| clock-names | {', '.join(cstr_list(phy['clock-names']))} |")
        rails = [k for k in phy if k.endswith("-supply")]
        if rails:
            add(f"| rails | {', '.join(rails)} |")
        has_seq = "qcom,qmp-phy-init-seq" in phy
        add(f"| qcom,qmp-phy-init-seq | {'present' if has_seq else 'ABSENT -> the init table lives in the driver driver-data'} |")
        add(f"| status | {cstr(phy.get('status', b''))} |")
    add("")

    # --- other UFS-adjacent blocks ---------------------------------------
    add("## 5. Other UFS-adjacent nodes in the DTB")
    add("")
    for path, props in nodes:
        if "ufsice" in path or "ufs_ice" in path or path.endswith("ufs_variant") or "gdsc_ufs" in path:
            compat = ", ".join(cstr_list(props.get("compatible", b""))) if "compatible" in props else "-"
            add(f"- `{path}` compatible `{compat}`")
    add("")
    add("## 6. What this does and does not give us")
    add("")
    add("- **Gives us**: the exact upstream source identity, every clock/reset/rail")
    add("  name, the MMIO windows, the SPI, the lane count and the PHY variant.  All")
    add("  of that is what a port usually loses weeks on.")
    add("- **Does not give us**: any loadable code.  The vendor driver is a Linux")
    add("  platform + SCSI host driver; XNU needs an IOService that publishes")
    add("  IOBlockStorageDevice.  The hardware sequencing ports over; the shape does")
    add("  not.")
    add("")

    text = "\n".join(lines)
    if args.out:
        with open(args.out, "w") as f:
            f.write(text + "\n")
        print(f"wrote {args.out} ({len(text)} bytes)")
    else:
        sys.stdout.write(text + "\n")


if __name__ == "__main__":
    main()
